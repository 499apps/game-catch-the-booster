// Writes dist/sw.js after `vite build`: a hand-written, cache-first service worker
// that precaches every file in dist/ under a content-hash version.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const BASE = '/games/catch-the-booster/';

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

const files = walk(dist)
  .map((p) => relative(dist, p).split(sep).join('/'))
  .filter((f) => f !== 'sw.js')
  .sort();

const hash = createHash('sha256');
for (const f of files) {
  hash.update(f);
  hash.update(readFileSync(join(dist, f)));
}
const version = hash.digest('hex').slice(0, 12);
const urls = ['', ...files.filter((f) => f !== 'index.html'), 'index.html'].map((f) => BASE + f);

const sw = `// Generated by scripts/build-sw.mjs. Do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = 'g499-catch-' + VERSION;
const BASE = ${JSON.stringify(BASE)};
const PRECACHE = ${JSON.stringify(urls, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) =>
        Promise.all(
          names.filter((n) => n.startsWith('g499-catch-') && n !== CACHE).map((n) => caches.delete(n)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return;
  const key = req.mode === 'navigate' ? BASE : url.pathname;
  event.respondWith(
    caches.open(CACHE).then((cache) =>
      cache.match(key).then((hit) => hit || fetch(req).then((res) => {
        if (res.ok && res.type === 'basic') cache.put(key, res.clone());
        return res;
      })),
    ),
  );
});
`;

writeFileSync(join(dist, 'sw.js'), sw);
console.log(`sw: precached ${urls.length} urls, version ${version}`);
